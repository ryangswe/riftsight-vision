// Vendoring a built runtime into a product, and checking it. One manifest, one toolkit commit.
//
// vendorInto() copies the files a product ships from a toolkit build (dist/, written by
// scripts/build.mjs) into one folder: the runtime, its declarations, ONNX Runtime's and OpenCV.js's
// files, the license texts, the hover spec when the commit has one, and a stand-alone checker. It
// writes cardvision-vendor.json beside them: the toolkit version, the commit, the options, the ONNX
// Runtime pin and every file's size and SHA-256. The folder is staged next to the target and swapped
// in by rename. A failed run restores the previous folder; an interrupted one is detected and
// restored on the next run.
//
// checkVendor() reads the manifest and reports what is wrong, as a list of messages: a file that
// changed, is missing or is extra; a file set that lacks what every vendored runtime has; a file
// that does not match the build of the manifest's commit (when that build is at hand); OpenCV.js that
// does not match the lock; a missing license file. Nothing here uses the network.

import { createHash } from "node:crypto";
import { cpSync, existsSync, lstatSync, mkdirSync, mkdtempSync, readFileSync, readdirSync, realpathSync, renameSync, rmSync, statSync, writeFileSync } from "node:fs";
import { basename, dirname, isAbsolute, join, relative, sep } from "node:path";
import { fileURLToPath } from "node:url";

export const MANIFEST = "cardvision-vendor.json";
export const CHECKER = "cardvision-vendor-check.mjs";
export const SPEC_FILE = "hover-spec.json";
export const OPENCV_FILES = ["opencv.mjs", "opencv_js.wasm", "opencv.mjs.LEGAL.txt"];
export const LICENSE_FILES = ["LICENSE", "NOTICE", "THIRD-PARTY-NOTICES.txt"];
/** The runtime files every product gets, beside the worker (worker-relative paths: one flat folder). */
export const RUNTIME_FILES = [
  "cardvision.js",
  "worker.js",
  "compute-session.js",
  "page-capture.js",
  "remote-release.js",
  "cardvision.js.LEGAL.txt",
  "worker.js.LEGAL.txt",
  "compute-session.js.LEGAL.txt",
  "page-capture.js.LEGAL.txt",
  "remote-release.js.LEGAL.txt",
];
/** The declarations: the entry shims beside the runtime, and types/ (tsc output of src/). */
export const TYPE_SHIMS = ["cardvision.d.ts", "compute-session.d.ts", "page-capture.d.ts", "remote-release.d.ts"];
export const NODE_TOOLS = ["node/verify-release.mjs", "node/package-zip.mjs", "node/store-upload.mjs"];
/** Every vendored folder lists these. */
export const REQUIRED = ["cardvision.js", "worker.js", "compute-session.js", "page-capture.js", "remote-release.js", ...TYPE_SHIMS, "types/index.d.ts", CHECKER, ...LICENSE_FILES];
/** What a product owns in the folder is named exactly; nothing is, by default. */
export const DEFAULT_UNMANAGED = [];

export const sha256 = (bytes) => createHash("sha256").update(bytes).digest("hex");
const readJson = (path) => JSON.parse(readFileSync(path, "utf-8"));
const HEX40 = /^[0-9a-f]{40}$/;
const SUFFIX_LIKE = /^\.(js|mjs|wasm|json|ts|d\.ts|txt|map)$/;

const CHECKER_TAIL = `
// Command line: node ${CHECKER} FOLDER
if (typeof process !== "undefined" && process.argv[1] && basename(process.argv[1]) === "${CHECKER}") {
  if (process.argv.length !== 3) {
    console.error("Usage: node ${CHECKER} FOLDER");
    process.exit(2);
  }
  const problems = checkVendor(process.argv[2]);
  if (problems.length > 0) {
    console.error(\`\${process.argv[2]} does not match ${MANIFEST}:\\n  \${problems.join("\\n  ")}\`);
    process.exit(1);
  }
  console.log(\`\${process.argv[2]} matches ${MANIFEST}. Checked: file hashes, file set, licenses, OpenCV lock as recorded. Not checked: the build of the commit.\`);
}
`;

/** The text of the stand-alone checker: this module, generated, plus a command line. Node built-ins only. */
export function standaloneChecker() {
  const source = readFileSync(fileURLToPath(import.meta.url), "utf-8");
  return `// Generated by the cardvision toolkit's npm run vendor from scripts/vendor-lib.mjs; do not edit.\n// Checks this folder against ${MANIFEST} (not against a build of the commit): node ${CHECKER} FOLDER\n${source}${CHECKER_TAIL}`;
}

/** What is wrong with a list of unmanaged rules: each is a folder ("dir/") or an exact file name. */
export function unmanagedProblems(rules) {
  if (!Array.isArray(rules) || rules.some((r) => typeof r !== "string")) return ["unmanaged must be a list of strings"];
  const problems = [];
  for (const rule of rules) {
    if (rule === "" || rule === "/" || isAbsolute(rule) || rule.includes("\\") || rule.split("/").includes("..") || rule.split("/").includes(".")) problems.push(`unmanaged rule "${rule}" is not a relative folder ("dir/") or file name`);
    else if (SUFFIX_LIKE.test(rule)) problems.push(`unmanaged rule "${rule}" looks like a file suffix; rules name a folder ("dir/") or one exact file`);
    else if (rule === MANIFEST) problems.push(`unmanaged rule "${rule}" names the manifest`);
  }
  return problems;
}

/** True when the folder-relative path is one the product owns: inside a rule's folder, or named exactly. */
export function isUnmanaged(path, unmanaged) {
  return unmanaged.some((rule) => (rule.endsWith("/") ? path.startsWith(rule) : path === rule));
}

/** Every file under `dir` (forward slashes, hidden names too), sorted, but the manifest. */
export function filesUnder(dir) {
  return readdirSync(dir, { recursive: true })
    .map((n) => String(n).split(sep).join("/"))
    .filter((n) => n !== MANIFEST && !statSync(join(dir, n), { throwIfNoEntry: false })?.isDirectory())
    .sort();
}

const walk = (dir) =>
  existsSync(dir)
    ? readdirSync(dir, { recursive: true })
        .map((n) => String(n).split(sep).join("/"))
        .filter((n) => !statSync(join(dir, n)).isDirectory())
        .sort()
    : [];

/** The ONNX Runtime files the built worker loads, by name. */
export function ortFilesOf(dist) {
  const worker = readFileSync(join(dist, "worker.js"), "utf-8");
  return [...new Set(worker.match(/ort-wasm-[a-z-]+(?:\.[a-z]+)*\.(?:wasm|mjs)/g) ?? [])].sort();
}

/** The version in pyproject.toml, the toolkit's one version. */
export function toolkitVersion(root) {
  const m = /^version\s*=\s*"([^"]+)"/m.exec(readFileSync(join(root, "pyproject.toml"), "utf-8"));
  if (!m) throw new Error("pyproject.toml has no version");
  return m[1];
}

/** What the lock pins for OpenCV, in the form the manifest keeps. */
function lockSummary(lock) {
  return { tag: lock.opencv.tag, commit: lock.opencv.commit, emsdk: lock.emsdk.tag, files: lock.built.files };
}

/**
 * The files a vendor run with these options takes from a checkout and its build.
 * Returns { files: [[folder-relative name, source path or null for the checker]], ort, lock }.
 */
export function planFiles({ root, dist, options }) {
  const { opencv, ortWasm, nodeTools } = options;
  const files = [];
  const need = (name, source) => {
    if (!existsSync(source)) throw new Error(`${source} is missing (build the toolkit first: npm run build in browser/)`);
    files.push([name, source]);
  };
  for (const name of RUNTIME_FILES) {
    // The LEGAL files exist only when the bundle had license comments.
    if (name.endsWith(".LEGAL.txt") && !existsSync(join(dist, name))) continue;
    need(name, join(dist, name));
  }
  need("LICENSE", join(root, "LICENSE"));
  need("NOTICE", join(root, "NOTICE"));
  need("THIRD-PARTY-NOTICES.txt", join(dist, "THIRD-PARTY-NOTICES.txt"));
  for (const name of TYPE_SHIMS) need(name, join(dist, name));
  const types = walk(join(dist, "types"));
  if (types.length === 0) throw new Error(`${join(dist, "types")} has no declarations (build the toolkit first: npm run build in browser/)`);
  for (const name of types) need(`types/${name}`, join(dist, "types", name));
  const ortNames = ortFilesOf(dist);
  if (ortNames.length === 0) throw new Error("the built worker names no ONNX Runtime file");
  if (ortWasm) for (const name of ortNames) need(name, join(dist, name));
  if (nodeTools) for (const name of NODE_TOOLS) need(name, join(dist, name));
  const lockPath = join(root, "browser", "opencv.lock.json");
  const lock = readJson(lockPath);
  if (opencv) for (const name of OPENCV_FILES) need(name, join(dist, name));
  const specPath = join(root, "docs", SPEC_FILE);
  if (existsSync(specPath)) files.push([SPEC_FILE, specPath]);
  files.push([CHECKER, null]);
  const version = readJson(join(root, "browser", "package.json")).dependencies?.["onnxruntime-web"];
  if (typeof version !== "string") throw new Error("browser/package.json has no onnxruntime-web dependency");
  return { files, ort: { version, files: ortNames }, lock, lockPath };
}

const real = (path) => {
  // The real path of the nearest existing ancestor, with the rest appended.
  let head = path;
  const rest = [];
  while (!existsSync(head)) {
    rest.unshift(basename(head));
    const up = dirname(head);
    if (up === head) break;
    head = up;
  }
  return join(realpathSync(head), ...rest);
};

const STAGE = (base) => new RegExp(`^\\.${base.replace(/[.*+?^${}()|[\]\\]/g, "\\$&")}-stage-[A-Za-z0-9]{6}(-old)?$`);

/** After an interrupted run: put the previous folder back, or clear what it left. */
function recover(into, warn) {
  const parent = dirname(into);
  if (!existsSync(parent)) return;
  const pattern = STAGE(basename(into));
  const left = readdirSync(parent).filter((n) => pattern.test(n));
  const olds = left.filter((n) => n.endsWith("-old"));
  if (!existsSync(into) && olds.length > 0) {
    if (olds.length > 1) throw new Error(`${into} is missing and ${olds.length} previous copies are left in ${parent} (${olds.join(", ")}): move the right one back to ${basename(into)} by hand, delete the others, and run again`);
    renameSync(join(parent, olds[0]), into);
    warn(`an earlier run was interrupted: ${into} was restored from ${olds[0]}`);
    left.splice(left.indexOf(olds[0]), 1);
  }
  for (const n of left) {
    try {
      rmSync(join(parent, n), { recursive: true, force: true });
      warn(`removed ${n}, left by an earlier run`);
    } catch (e) {
      warn(`could not remove ${join(parent, n)}: ${e.message}`);
    }
  }
}

/** Is a path in a folder that a vendor run with --adopt may replace (a hand-vendored runtime)? */
const legacy = (name, planned) =>
  planned.has(name) || name === "VENDOR.json" || name.startsWith("types/") || name.startsWith("node/") || name.endsWith(".d.ts") || name.endsWith(".LEGAL.txt") || /^(ort-wasm|opencv)/.test(name) || name === "LICENSE" || name === "NOTICE";

/**
 * Copy the runtime from a toolkit build into `into`.
 *   root       the toolkit checkout (holds browser/opencv.lock.json, docs/, LICENSE, NOTICE, pyproject.toml)
 *   dist       the build of that commit (browser/dist)
 *   commit     the toolkit commit the build was made from
 *   opencv     false to leave OpenCV.js out (a product with no geometric stage)
 *   ortWasm    false to leave ONNX Runtime's WebAssembly files out (a product that copies its own);
 *              the manifest names the version and files either way
 *   nodeTools  true to add dist/node/*.mjs
 *   unmanaged  folders ("dir/") and exact file names the product owns in the folder; kept across a run
 *   adopt      true to replace a non-empty folder that has no manifest yet (a hand-vendored runtime)
 *   warn       called with a message for what went wrong but did not stop the run
 *   hooks      test seams: { beforeSwap(stage), betweenRenames() }
 */
export function vendorInto({ root, dist, into, commit, opencv = true, ortWasm = true, nodeTools = false, unmanaged = DEFAULT_UNMANAGED, adopt = false, warn = () => {}, hooks = {} }) {
  if (!HEX40.test(commit)) throw new Error(`commit must be a full 40-character SHA, not "${commit}"`);
  const bad = unmanagedProblems(unmanaged);
  if (bad.length > 0) throw new Error(bad.join("; "));
  if (existsSync(into) && lstatSync(into).isSymbolicLink()) throw new Error(`${into} is a symbolic link: name the folder itself`);
  const inside = relative(realpathSync(root), real(into));
  const around = relative(real(into), realpathSync(root));
  if ((!inside.startsWith("..") && !isAbsolute(inside)) || (!around.startsWith("..") && !isAbsolute(around))) throw new Error(`${into} is inside the toolkit checkout (or holds it): vendor into a product's folder`);
  recover(into, warn);

  const options = { opencv, ortWasm, nodeTools };
  const plan = planFiles({ root, dist, options });
  const names = new Set(plan.files.map(([n]) => n));
  const clash = [...names].filter((n) => isUnmanaged(n, unmanaged));
  if (clash.length > 0) throw new Error(`unmanaged rules cover files the tool vendors: ${clash.slice(0, 5).join(", ")}`);
  if (opencv) {
    for (const name of OPENCV_FILES) {
      const pinned = plan.lock.built.files[name];
      if (pinned) {
        const bytes = readFileSync(join(dist, name));
        if (sha256(bytes) !== pinned.sha256 || bytes.length !== pinned.bytes) throw new Error(`${name} in the build does not match opencv.lock.json`);
      }
    }
  }

  // What is in the target now: refuse to delete what the tool did not put there.
  if (existsSync(into)) {
    if (!statSync(into).isDirectory()) throw new Error(`${into} is not a folder`);
    const present = walk(into).filter((n) => n !== MANIFEST);
    let old = null;
    if (existsSync(join(into, MANIFEST))) {
      try {
        old = readJson(join(into, MANIFEST));
      } catch {
        throw new Error(`${join(into, MANIFEST)} is not valid JSON: fix or delete it`);
      }
    }
    if (!old && readdirSync(into).length > 0 && !adopt) {
      throw new Error(`${into} is not empty and has no ${MANIFEST}: the tool replaces a folder it made. Use --adopt to replace a hand-vendored runtime, or choose another folder`);
    }
    const known = new Set(Object.keys(old?.files ?? {}));
    const strays = present.filter((n) => !known.has(n) && !isUnmanaged(n, unmanaged) && !(adopt && !old && legacy(n, names)));
    if (strays.length > 0) {
      const shown = strays.slice(0, 10).join(", ");
      throw new Error(`${into} holds ${strays.length} file(s) the tool did not put there and would delete: ${shown}${strays.length > 10 ? ", ..." : ""}. Move them out, or name them with --unmanaged (a folder "dir/" or an exact file name)`);
    }
  }

  mkdirSync(dirname(into), { recursive: true });
  const stage = mkdtempSync(join(dirname(into), `.${basename(into)}-stage-`));
  const old = `${stage}-old`;
  let swapped = false;
  try {
    const files = {};
    const checkerText = standaloneChecker();
    for (const [name, source] of plan.files) {
      const bytes = source === null ? Buffer.from(checkerText) : readFileSync(source);
      mkdirSync(dirname(join(stage, name)), { recursive: true });
      writeFileSync(join(stage, name), bytes, { mode: 0o644 });
      files[name] = { bytes: bytes.length, sha256: sha256(bytes) };
    }
    // What the product owns in the folder goes across.
    if (existsSync(into)) {
      for (const name of walk(into)) {
        if (isUnmanaged(name, unmanaged)) {
          mkdirSync(dirname(join(stage, name)), { recursive: true });
          cpSync(join(into, name), join(stage, name));
        }
      }
    }
    const manifest = {
      schemaVersion: 1,
      toolkit: { version: toolkitVersion(root), commit },
      options,
      unmanaged,
      ort: plan.ort,
      opencv: opencv ? { ...lockSummary(plan.lock), lockSha256: sha256(readFileSync(plan.lockPath)) } : null,
      files: Object.fromEntries(Object.entries(files).sort(([a], [b]) => (a < b ? -1 : 1))),
    };
    const tmp = join(stage, `.${MANIFEST}.tmp`);
    writeFileSync(tmp, `${JSON.stringify(manifest, null, 2)}\n`);
    renameSync(tmp, join(stage, MANIFEST));
    hooks.beforeSwap?.(stage);
    let moved = false;
    try {
      if (existsSync(into)) {
        renameSync(into, old);
        moved = true;
      }
      hooks.betweenRenames?.();
      renameSync(stage, into);
      swapped = true;
    } catch (e) {
      if (moved && !existsSync(into)) renameSync(old, into);
      throw e;
    }
    try {
      rmSync(old, { recursive: true, force: true });
    } catch (e) {
      warn(`${into} is updated, but the previous copy ${old} could not be removed: ${e.message}`);
    }
    return manifest;
  } finally {
    if (!swapped) rmSync(stage, { recursive: true, force: true });
  }
}

/**
 * Pick the build to compare with: the checkout's build, when it is the manifest's commit and was made
 * from a clean tree. Returns { toolkit } or { reason } (why the comparison cannot run).
 */
export function selectBuild({ root, dist, head, manifestCommit }) {
  if (!head) return { reason: "this checkout is not a git checkout" };
  if (head !== manifestCommit) return { reason: `this checkout is at ${head.slice(0, 12)}, the manifest is for ${manifestCommit.slice(0, 12)}` };
  const infoPath = join(dist, "build-info.json");
  if (!existsSync(infoPath)) return { reason: "dist/build-info.json is missing (run npm run build)" };
  let info;
  try {
    info = readJson(infoPath);
  } catch {
    return { reason: "dist/build-info.json is not valid JSON" };
  }
  if (info.commit !== manifestCommit) return { reason: `dist/ was built from ${String(info.commit).slice(0, 12)}, not ${manifestCommit.slice(0, 12)} (run npm run build)` };
  if (info.dirty) return { reason: "dist/ was built from a tree with changes (run npm run build on a clean tree)" };
  return { toolkit: { root, dist, commit: manifestCommit } };
}

/**
 * What is wrong with a vendored folder; an empty list when nothing is.
 *   toolkit  optional { root, dist, commit }: the checkout, its build and the commit of that build
 *            (see selectBuild). The build is compared only when `commit` is the manifest's commit.
 */
export function checkVendor(dir, toolkit) {
  const problems = [];
  const manifestPath = join(dir, MANIFEST);
  if (!existsSync(manifestPath)) return [`${MANIFEST} is missing from ${dir} (vendor with npm run vendor)`];
  let m;
  try {
    m = readJson(manifestPath);
  } catch {
    return [`${MANIFEST} is not valid JSON`];
  }
  if (m.schemaVersion !== 1 || !m.files || typeof m.files !== "object" || !HEX40.test(m.toolkit?.commit ?? "")) {
    return [`${MANIFEST} is not a version 1 manifest with a toolkit commit and a file list`];
  }
  const short = m.toolkit.commit.slice(0, 12);
  const unmanaged = Array.isArray(m.unmanaged) ? m.unmanaged : [];
  problems.push(...unmanagedProblems(m.unmanaged ?? []));
  const listed = Object.keys(m.files);
  for (const n of listed) if (isUnmanaged(n, unmanaged)) problems.push(`${n} is listed in ${MANIFEST} and also covered by an unmanaged rule`);
  const present = filesUnder(dir).filter((n) => !isUnmanaged(n, unmanaged));

  for (const n of present) if (!listed.includes(n)) problems.push(`${n} is in the folder but not in ${MANIFEST}`);
  for (const n of listed) {
    if (!present.includes(n)) problems.push(`${n} is listed in ${MANIFEST} but missing`);
    else if (sha256(readFileSync(join(dir, n))) !== m.files[n].sha256) {
      problems.push(`${n} differs from the SHA-256 in ${MANIFEST} (all files must come from commit ${short}; was one updated alone?)`);
    }
  }

  // What every vendored folder lists, and the licenses.
  for (const n of REQUIRED) if (!listed.includes(n)) problems.push(`${n} is not listed in ${MANIFEST}`);
  for (const n of [...LICENSE_FILES, ...(listed.includes("opencv.mjs.LEGAL.txt") ? ["opencv.mjs.LEGAL.txt"] : [])]) {
    if (listed.includes(n) && present.includes(n) && statSync(join(dir, n)).size === 0) problems.push(`license file ${n} is empty`);
  }

  // The options, and the ONNX Runtime pin the product must ship.
  const o = m.options;
  if (!o || typeof o.opencv !== "boolean" || typeof o.ortWasm !== "boolean" || typeof o.nodeTools !== "boolean") problems.push(`${MANIFEST} has no options (opencv, ortWasm, nodeTools)`);
  const ort = m.ort;
  if (!ort || typeof ort.version !== "string" || ort.version === "" || !Array.isArray(ort.files) || ort.files.length === 0) problems.push(`${MANIFEST} has no ort pin (version and files)`);
  else if (o?.ortWasm) for (const n of ort.files) if (!listed.includes(n)) problems.push(`ONNX Runtime file ${n} is not listed in ${MANIFEST}`);

  // OpenCV: required when an OpenCV file is listed; the files against the lock recorded for this commit.
  const opencvListed = OPENCV_FILES.filter((n) => listed.includes(n));
  if (opencvListed.length > 0 && !m.opencv) problems.push(`OpenCV files are listed but ${MANIFEST} has no opencv lock`);
  if (m.opencv) {
    for (const n of OPENCV_FILES) if (!listed.includes(n)) problems.push(`OpenCV file ${n} is not listed in ${MANIFEST}`);
    for (const [n, pin] of Object.entries(m.opencv.files ?? {})) {
      if (listed.includes(n) && m.files[n].sha256 !== pin.sha256) problems.push(`${n} does not match the OpenCV lock recorded in ${MANIFEST}`);
    }
    if (o && o.opencv === false) problems.push(`${MANIFEST} has an opencv lock but its options say OpenCV.js is left out`);
  } else if (o?.opencv === true) problems.push(`${MANIFEST} options say OpenCV.js is vendored but there is no opencv lock`);

  // The build of the manifest's commit, when at hand: the lock, the file set, every file.
  if (toolkit && toolkit.commit === m.toolkit.commit) {
    const lockPath = join(toolkit.root, "browser", "opencv.lock.json");
    if (m.opencv && existsSync(lockPath)) {
      const lock = readJson(lockPath);
      if (sha256(readFileSync(lockPath)) !== m.opencv.lockSha256) problems.push(`the OpenCV lock of commit ${short} differs from the one recorded in ${MANIFEST}`);
      for (const [n, pin] of Object.entries(lock.built.files)) {
        if (listed.includes(n) && m.files[n].sha256 !== pin.sha256) problems.push(`${n} does not match opencv.lock.json of the toolkit`);
      }
    }
    let plan = null;
    if (o) {
      try {
        plan = planFiles({ root: toolkit.root, dist: toolkit.dist, options: o });
      } catch (e) {
        problems.push(`the build of commit ${short} cannot supply the files the manifest's options ask for: ${e.message}`);
      }
    }
    if (plan) {
      const expected = plan.files.map(([n]) => n);
      for (const n of expected) if (!listed.includes(n)) problems.push(`${n} is in the build of commit ${short} for these options but not in ${MANIFEST}`);
      for (const n of listed) if (!expected.includes(n)) problems.push(`${n} is in ${MANIFEST} but not in the build of commit ${short} for these options`);
      if (JSON.stringify(plan.ort) !== JSON.stringify(ort)) problems.push(`the ONNX Runtime pin in ${MANIFEST} differs from the build of commit ${short}`);
      if (toolkitVersion(toolkit.root) !== m.toolkit.version) problems.push(`the toolkit version in ${MANIFEST} differs from the checkout's`);
      for (const [n, source] of plan.files) {
        if (!present.includes(n)) continue;
        const have = readFileSync(join(dir, n));
        if (source === null ? have.toString("utf-8") !== standaloneChecker() : sha256(readFileSync(source)) !== sha256(have)) {
          problems.push(`${n} differs from the build of commit ${short}`);
        }
      }
    }
  }
  return problems;
}
